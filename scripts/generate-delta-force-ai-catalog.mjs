const ensureCleanDir = (dir) => {
  fs.mkdirSync(dir, { recursive: true });
  for (const entry of fs.readdirSync(dir)) {
    if (entry.endsWith('.md')) {
      fs.unlinkSync(path.join(dir, entry));
    }
  }
};

const toFrontmatterLines = (meta) => {
  const orderedKeys = [
    'id',
    'title',
    'type',
    'author',
    'version',
    'category',
    'trigger',
    'domain',
    'verification_tier',
    'verified_on',
    'status',
    'source_urls',
    'research_basis_urls',
    'tags',
    'games',
    'shared_tags_team',
    'shared_tags_asset',
    'sections_supported',
    'required_inputs',
    'outputs',
    'depends_on_skills',
    'depends_on_knowledge',
    'linked_skills',
  ];

  return orderedKeys
    .filter((key) => key in meta && meta[key] !== undefined)
    .map((key) => `${key}: ${JSON.stringify(meta[key])}`);
};

const knowledgeMarkdown = (item) => {
  const meta = {
    ...defaultMeta,
    id: item.id,
    title: item.title,
    type: 'knowledge',
    category: item.category,
    domain: 'delta-force',
    verification_tier: item.verification_tier,
    status: item.status,
    source_urls: item.source_urls,
    tags: item.tags,
    games: item.games || defaultMeta.games,
    shared_tags_team: item.shared_tags_team,
    shared_tags_asset: item.shared_tags_asset,
    linked_skills: item.linked_skills,
  };

  return [
    '---',
    ...toFrontmatterLines(meta),
    '---',
    '',
    '## Summary',
    item.summary,
    '',
    '## Key Facts',
    ...item.facts.map((fact) => `- ${fact}`),
    '',
    '## How To Use',
    ...item.usage.map((entry) => `- ${entry}`),
    '',
  ].join('\n');
};

const skillMarkdown = (item) => {
  const meta = {
    ...defaultMeta,
    id: item.id,
    title: item.title,
    type: 'skill',
    category: item.category,
    trigger: item.trigger,
    domain: 'delta-force',
    status: 'active',
    research_basis_urls: item.research_basis_urls,
    tags: item.tags,
    games: item.games || defaultMeta.games,
    shared_tags_team: item.shared_tags_team,
    shared_tags_asset: item.shared_tags_asset,
    sections_supported: item.sections_supported,
    required_inputs: item.required_inputs,
    outputs: item.outputs,
    depends_on_skills: item.depends_on_skills,
    depends_on_knowledge: item.depends_on_knowledge,
  };

  return [
    '---',
    ...toFrontmatterLines(meta),
    '---',
    '',
    '## Objective',
    item.objective,
    '',
    '## Workflow',
    ...item.steps.map((step, index) => `${index + 1}. ${step}`),
    '',
    '## Notes',
    ...item.notes.map((note) => `- ${note}`),
    '',
  ].join('\n');
};

const writeCatalog = () => {
  ensureCleanDir(knowledgeDir);
  ensureCleanDir(skillDir);

  for (const item of knowledgeItems) {
    fs.writeFileSync(path.join(knowledgeDir, `${item.id}.md`), knowledgeMarkdown(item), 'utf8');
  }

  for (const item of skillItems) {
    fs.writeFileSync(path.join(skillDir, `${item.id}.md`), skillMarkdown(item), 'utf8');
  }

  console.log(`Generated ${knowledgeItems.length} knowledge files and ${skillItems.length} skill files.`);
};

writeCatalog();
